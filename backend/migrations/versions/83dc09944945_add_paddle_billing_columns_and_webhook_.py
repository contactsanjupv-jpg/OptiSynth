def _ddl(statement: str) -> str:
    """Return `statement` as it must be sent to the CURRENT database.

    This migration was written for SQLite, but PostgreSQL is the supported production database
    (README, .env.example, requirements.txt). Two SQLite-isms in table definitions do not exist there:
      * `INTEGER PRIMARY KEY AUTOINCREMENT` is a syntax error in PostgreSQL. It becomes
        `INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`, the same behaviour: the database
        assigns the next id unless one is given.
      * `REAL` is an 8-byte float in SQLite but a 4-byte float in PostgreSQL, which would silently round
        every stored prediction/target value to ~7 digits. It becomes `DOUBLE PRECISION` (8 bytes).
    On SQLite the statement is returned UNCHANGED, so a SQLite database is created exactly as before.
    (Self-contained on purpose: Alembic loads each revision file by itself, so it cannot rely on
    importing a shared helper from every working directory.)"""
    if op.get_context().dialect.name != "postgresql":
        return statement
    statement = statement.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", statement)


