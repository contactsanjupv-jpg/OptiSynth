    statement = statement.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", statement)


